let currentLocale = (typeof localStorage !== 'undefined' && localStorage.getItem('locale')) || 'tr';

export function getLocale() { return currentLocale; }

export function setLocale(loc) {
  if (!STRINGS[loc]) return;
  currentLocale = loc;
  try { localStorage.setItem('locale', loc); } catch (_) {}
  document.documentElement.lang = loc;
  applyTranslations();
  document.dispatchEvent(new CustomEvent('locale-changed', { detail: loc }));
}

/**
 * Translate a key. Supports {placeholder} substitution.
 * Falls back to English then to the key.
 */
export function t(key, params) {
  const dict = STRINGS[currentLocale] || STRINGS.en;
  let str = dict[key];
  if (str === undefined) str = STRINGS.en[key];
  if (str === undefined) return key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.split('{' + k + '}').join(String(v));
    }
  }
  return str;
}

/**
 * Apply translations to all elements with data-i18n* attributes.
 * Must be called after DOM is ready and on every locale change.
 */
export function applyTranslations(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  scope.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  scope.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
  });
}

export function initI18n() {
  document.documentElement.lang = currentLocale;
  applyTranslations();
}
